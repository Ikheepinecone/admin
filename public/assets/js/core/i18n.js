  var STORAGE_KEY = 'pk.lang';
  var lang = 'mn';
  try {
    var saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'mn') lang = saved;
  } catch (e) { /* storage unavailable: keep default */ }

  function t(key, vars) {
    var str = (DICT[lang] && DICT[lang][key]) || DICT.mn[key] || key;
    if (vars) {
      str = str.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? vars[k] : m; });
    }
    return str;
  }

  function loc(obj) {
    if (obj == null) return '';
    if (typeof obj === 'string') return obj;
    return obj[lang] || obj.mn || obj.en || '';
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll('[data-i18n]').forEach(function (el) { el.textContent = t(el.getAttribute('data-i18n')); });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) { el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder'))); });
    root.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) { el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label'))); });
  }

  function setLang(next) {
    if (next !== 'mn' && next !== 'en') return;
    try { localStorage.setItem(STORAGE_KEY, next); } catch (e) { /* ignore */ }
    location.reload();
  }

  document.documentElement.lang = lang;

  /** Add strings for a section of the app (e.g. the admin dashboard). */
  function extend(extra) {
    Object.keys(extra).forEach(function (l) { DICT[l] = Object.assign(DICT[l] || {}, extra[l]); });
  }

  PK.i18n = { t: t, loc: loc, apply: apply, setLang: setLang, extend: extend, get lang() { return lang; } };
  PK.t = t;
  PK.loc = loc;
